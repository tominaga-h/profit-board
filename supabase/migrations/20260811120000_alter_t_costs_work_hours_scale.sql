-- ============================================================
-- ProfitBoard 稼働時間の小数桁を拡張
--
-- 15分単位（0.25h）で入力したいという要望に対応する。
-- NUMERIC(6,1) のままでは第2位以下が DB 側で黙って丸められ、
-- 画面の表示値・計算した金額と保存値がずれる。
--
-- 桁数は6のままなので、上限は 99999.9 から 9999.99 へ下がる。
-- 月次の稼働時間としては十分で、変更後は work_days（NUMERIC(6,2)）と上限が揃う。
-- 既存データの最大は 120.0h のため、桁あふれは起きない。
-- ============================================================

ALTER TABLE public.t_costs
  ALTER COLUMN work_hours TYPE NUMERIC(6, 2);
